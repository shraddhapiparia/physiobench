"""Unit tests for src/bdr.py.

Every expected value below is worked out by hand in the comments; none is
generated by calling the implementation. Volumes are mL (as in NHANES),
GLI predictions are litres.
"""

import math
import sys
import unittest
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
import bdr  # noqa: E402

CFG = bdr.load_config()
NA = np.nan


def case(**kw) -> pd.Series:
    """One participant row; defaults are an adult with A/B grades and no change."""
    row = dict(SEQN=1, is_adult=True,
               SPXNFEV1=2500.0, SPXBFEV1=2500.0, SPXNFVC=3000.0, SPXBFVC=3000.0,
               gli_fev1_pred=3.0, gli_fvc_pred=4.0, gli_fev1fvc_lln=0.70,
               fev1_pre_grade_AB=True, fvc_pre_grade_AB=True,
               fev1_post_grade_AB=True, fvc_post_grade_AB=True)
    row.update(kw)
    out = bdr.classify(pd.DataFrame([row]), CFG).iloc[0]
    # numpy.bool_ -> bool so assertIs(x, True/False) is exact; <NA> is kept.
    return {k: bool(v) if isinstance(v, np.bool_) else v for k, v in out.items()}


def is_na(x) -> bool:
    return x is pd.NA or (isinstance(x, float) and math.isnan(x))


class TestConfigMatchesSpecification(unittest.TestCase):
    def test_thresholds_and_operators(self):
        g, a = CFG["bdr"]["gina"], CFG["bdr"]["ats_ers"]
        self.assertEqual((g["pct_baseline"]["operator"], g["pct_baseline"]["threshold"]), (">=", 12))
        self.assertEqual((g["abs_change_ml"]["operator"], g["abs_change_ml"]["threshold"]), (">=", 200))
        self.assertEqual((a["pct_predicted"]["operator"], a["pct_predicted"]["threshold"]), (">", 10))
        fr = CFG["obstruction"]["fixed_ratio"]["fev1_fvc"]
        self.assertEqual((fr["operator"], fr["threshold"]), ("<", 0.70))
        self.assertEqual(CFG["obstruction"]["lln"]["fev1_fvc"]["operator"], "<")


class TestChanges(unittest.TestCase):
    def test_1_fev1_2_10_to_2_45(self):
        # 2.10 L -> 2.45 L = 2100 -> 2450 mL: +350 mL; 100*350/2100 = 16.6667 %
        r = case(SPXNFEV1=2100.0, SPXBFEV1=2450.0)
        self.assertEqual(r["fev1_bd_change_ml"], 350.0)
        self.assertAlmostEqual(r["fev1_bd_change_pct_baseline"], 16.6667, places=4)
        # vs predicted 3.0 L: 100*350/3000 = 11.6667 %
        self.assertAlmostEqual(r["fev1_bd_change_pct_pred"], 11.6667, places=4)

    def test_7_negative_change_retained(self):
        # 2500 -> 2300: -200 mL; -8 %; vs pred 3000: -6.6667 %
        r = case(SPXBFEV1=2300.0, SPXBFVC=2900.0)
        self.assertEqual(r["fev1_bd_change_ml"], -200.0)
        self.assertAlmostEqual(r["fev1_bd_change_pct_baseline"], -8.0, places=10)
        self.assertAlmostEqual(r["fev1_bd_change_pct_pred"], -6.6667, places=4)
        self.assertIs(r["gina_bdr"], False)
        self.assertIs(r["ats_ers_bdr"], False)
        self.assertEqual(r["gina_bdr_status"], "negative")

    def test_9_zero_and_negative_denominators(self):
        for bad in (0.0, -100.0, np.inf):
            r = case(SPXNFEV1=bad, SPXBFEV1=2450.0)
            self.assertTrue(is_na(r["fev1_bd_change_ml"]), bad)
            self.assertTrue(is_na(r["fev1_bd_change_pct_baseline"]), bad)
            self.assertTrue(is_na(r["gina_fev1_only"]), bad)
            self.assertFalse(r["primary_bdr_eligible"], bad)
        for bad_pred in (0.0, -1.0, NA):
            r = case(SPXNFEV1=2100.0, SPXBFEV1=2450.0, gli_fev1_pred=bad_pred)
            self.assertEqual(r["fev1_bd_change_ml"], 350.0)       # change still defined
            self.assertTrue(is_na(r["fev1_bd_change_pct_pred"]))
            self.assertTrue(is_na(r["ats_ers_fev1_only"]))
            self.assertIs(r["gina_fev1_only"], True)                # GINA needs no prediction


class TestGinaBoundaries(unittest.TestCase):
    def test_2_exact_12pct_and_200ml_pass(self):
        # 2000 -> 2240: +240 mL, exactly 12.000 %  -> positive (>= 12, >= 200)
        self.assertIs(case(SPXNFEV1=2000.0, SPXBFEV1=2240.0)["gina_fev1_only"], True)
        # 1500 -> 1700: exactly +200 mL, 13.33 %  -> positive
        self.assertIs(case(SPXNFEV1=1500.0, SPXBFEV1=1700.0)["gina_fev1_only"], True)
        # 1666 -> 1866: exactly +200 mL and 12.005 % -> positive
        self.assertIs(case(SPXNFEV1=1666.0, SPXBFEV1=1866.0)["gina_fev1_only"], True)

    def test_2b_just_below_boundaries_fail(self):
        # 2000 -> 2239: +239 mL, 11.95 % -> negative (fails %)
        self.assertIs(case(SPXNFEV1=2000.0, SPXBFEV1=2239.0)["gina_fev1_only"], False)
        # 1000 -> 1199: +199 mL, 19.9 % -> negative (fails mL)
        self.assertIs(case(SPXNFEV1=1000.0, SPXBFEV1=1199.0)["gina_fev1_only"], False)


class TestAtsErsBoundary(unittest.TestCase):
    def test_3_exactly_10pct_of_predicted_does_not_pass(self):
        # pred 3.0 L = 3000 mL; +300 mL = exactly 10 % of predicted -> negative (> 10)
        r = case(SPXNFEV1=2500.0, SPXBFEV1=2800.0, gli_fev1_pred=3.0)
        self.assertAlmostEqual(r["fev1_bd_change_pct_pred"], 10.0, places=12)
        self.assertIs(r["ats_ers_fev1_only"], False)
        # +301 mL = 10.033 % -> positive
        self.assertIs(case(SPXNFEV1=2500.0, SPXBFEV1=2801.0, gli_fev1_pred=3.0)["ats_ers_fev1_only"], True)


class TestGuidelineDifferences(unittest.TestCase):
    def test_4_gina_positive_ats_ers_negative(self):
        # FEV1 1500 -> 1700: +200 mL, 13.33 % baseline (GINA yes); 200/3000 = 6.67 % pred (ATS no)
        # FVC 3000 -> 3000: no change.
        r = case(SPXNFEV1=1500.0, SPXBFEV1=1700.0, gli_fev1_pred=3.0)
        self.assertIs(r["gina_bdr"], True)
        self.assertIs(r["ats_ers_bdr"], False)

    def test_5_ats_ers_positive_gina_negative(self):
        # FEV1 3000 -> 3350: +350 mL, 11.67 % baseline (GINA no); 350/3000 = 11.67 % pred (ATS yes)
        r = case(SPXNFEV1=3000.0, SPXBFEV1=3350.0, gli_fev1_pred=3.0)
        self.assertIs(r["gina_bdr"], False)
        self.assertIs(r["ats_ers_bdr"], True)

    def test_6_fvc_only_response(self):
        # FEV1 2500 -> 2550: +50 mL (2 %; 1.67 % pred) -> no on both
        # FVC 3000 -> 3450: +450 mL, 15 % baseline (GINA yes); 450/4000 = 11.25 % pred (ATS yes)
        r = case(SPXBFEV1=2550.0, SPXBFVC=3450.0, gli_fvc_pred=4.0)
        self.assertIs(r["gina_fev1_only"], False)
        self.assertIs(r["gina_fvc_only"], True)
        self.assertIs(r["gina_bdr"], True)
        self.assertIs(r["ats_ers_fev1_only"], False)
        self.assertIs(r["ats_ers_fvc_only"], True)
        self.assertIs(r["ats_ers_bdr"], True)


class TestMissingAndThreeValuedLogic(unittest.TestCase):
    def test_8_missing_post_is_not_negative(self):
        r = case(SPXBFEV1=NA, SPXBFVC=NA)
        self.assertTrue(is_na(r["gina_bdr"]))
        self.assertTrue(is_na(r["ats_ers_bdr"]))
        self.assertEqual(r["gina_bdr_status"], "not_assessable")
        self.assertEqual(r["ats_ers_bdr_status"], "not_assessable")
        self.assertFalse(r["primary_bdr_eligible"])
        self.assertEqual(r["primary_bdr_exclusion_reason"], "missing_pre_or_post_fev1_fvc")

    def test_8b_missing_pre_and_missing_predictions(self):
        r = case(SPXNFEV1=NA)
        self.assertTrue(is_na(r["fev1_bd_change_ml"]))
        r = case(gli_fev1_pred=NA, gli_fvc_pred=NA)
        self.assertTrue(is_na(r["ats_ers_bdr"]))
        self.assertIs(r["gina_bdr"], False)          # GINA still assessable (no change)
        self.assertEqual(r["primary_bdr_exclusion_reason"], "no_valid_gli_prediction")

    def test_12_three_valued_or(self):
        # Direct truth table (Kleene OR), expectations written by hand.
        a = pd.Series([True, True, False, False, pd.NA, pd.NA], dtype="boolean")
        b = pd.Series([pd.NA, False, pd.NA, False, pd.NA, True], dtype="boolean")
        got = bdr.or3(a, b).tolist()
        self.assertEqual(got, [True, True, pd.NA, False, pd.NA, True])

    def test_12b_or_positive_with_other_component_missing(self):
        # FEV1 +240/2000 = 12 % (GINA yes), FVC post missing -> GINA positive overall
        r = case(SPXNFEV1=2000.0, SPXBFEV1=2240.0, SPXBFVC=NA)
        self.assertIs(r["gina_bdr"], True)
        self.assertEqual(r["gina_bdr_status"], "positive")
        # FEV1 no change (negative), FVC missing -> not assessable, NOT negative
        r = case(SPXBFVC=NA)
        self.assertIs(r["gina_fev1_only"], False)
        self.assertTrue(is_na(r["gina_bdr"]))
        self.assertEqual(r["gina_bdr_status"], "not_assessable")


class TestObstruction(unittest.TestCase):
    def test_10_fixed_ratio_boundary(self):
        # 1400/2000 = exactly 0.70 -> not obstructed (< 0.70); 1399/2000 = 0.6995 -> obstructed
        self.assertIs(case(SPXNFEV1=1400.0, SPXNFVC=2000.0)["obstruction_fixed_ratio"], False)
        self.assertIs(case(SPXNFEV1=1399.0, SPXNFVC=2000.0)["obstruction_fixed_ratio"], True)

    def test_11_ratio_equal_to_lln(self):
        # ratio 0.70 vs LLN 0.70 -> not below; vs LLN 0.7001 -> below
        self.assertIs(case(SPXNFEV1=1400.0, SPXNFVC=2000.0, gli_fev1fvc_lln=0.70)["obstruction_gli_lln"], False)
        self.assertIs(case(SPXNFEV1=1400.0, SPXNFVC=2000.0, gli_fev1fvc_lln=0.7001)["obstruction_gli_lln"], True)

    def test_obstruction_not_assessable(self):
        r = case(SPXNFVC=NA)
        self.assertTrue(is_na(r["obstruction_fixed_ratio"]))
        self.assertTrue(is_na(r["obstruction_gli_lln"]))
        r = case(gli_fev1fvc_lln=NA)
        self.assertTrue(is_na(r["obstruction_gli_lln"]))
        self.assertIs(r["obstruction_fixed_ratio"], False)   # 2500/3000 = 0.833


class TestPopulationAndEligibility(unittest.TestCase):
    def test_13_pediatric_no_gina(self):
        # GINA-qualifying change (+240 mL, 12 %) in a child -> GINA not applied
        r = case(is_adult=False, SPXNFEV1=2000.0, SPXBFEV1=2240.0)
        self.assertTrue(is_na(r["gina_bdr"]))
        self.assertTrue(is_na(r["gina_fev1_only"]))
        self.assertEqual(r["gina_bdr_status"], "not_applicable_pediatric")
        self.assertIs(r["ats_ers_fev1_only"], False)           # 240/3000 = 8 % pred, computed
        self.assertFalse(r["primary_bdr_eligible"])
        self.assertEqual(r["primary_bdr_exclusion_reason"], "not_adult")

    def test_13b_pediatric_fixed_ratio_not_interpreted(self):
        # Child with 1399/2000 = 0.6995: calculation kept, adult label blank
        r = case(is_adult=False, SPXNFEV1=1399.0, SPXNFVC=2000.0)
        self.assertIs(r["obstruction_fixed_ratio"], True)
        self.assertTrue(is_na(r["obstruction_fixed_ratio_adult"]))
        self.assertEqual(r["obstruction_fixed_ratio_adult_status"], "not_applicable_pediatric")
        # Same values in an adult -> interpreted
        r = case(SPXNFEV1=1399.0, SPXNFVC=2000.0)
        self.assertIs(r["obstruction_fixed_ratio_adult"], True)
        self.assertEqual(r["obstruction_fixed_ratio_adult_status"], "positive")

    def test_low_quality_keeps_classification_but_not_eligible(self):
        # Grade C on post-BD FVC: classification computed, eligibility False
        r = case(SPXNFEV1=2000.0, SPXBFEV1=2240.0, fvc_post_grade_AB=False)
        self.assertIs(r["gina_bdr"], True)
        self.assertFalse(r["primary_bdr_eligible"])
        self.assertEqual(r["primary_bdr_exclusion_reason"], "grade_not_AB")

    def test_eligible_case(self):
        r = case(SPXNFEV1=2000.0, SPXBFEV1=2240.0)
        self.assertTrue(r["primary_bdr_eligible"])
        self.assertEqual(r["primary_bdr_exclusion_reason"], "")


if __name__ == "__main__":
    unittest.main()
